// ── Checks on the string tables ────────────────────────────────────────────
const problems = [];
const missing = LANGS.filter(l => !S[l]);
if (missing.length) problems.push(`no strings table for: ${missing.join(', ')}`);

// Keys that may read exactly like English in another language: the studio's
// name as Home's title, and the logo's label where "home" is the local word.
const SAME_ON_PURPOSE = new Set(['home.title', 'brandLabel']);
const placeholders = (v) => [...String(v).matchAll(/\{(\w+)\}/g)].map(m => m[1]).sort().join(',');
const compare = (en, other, lang, at) => {
  if (Array.isArray(en)) {
    if (!Array.isArray(other) || other.length !== en.length) return problems.push(`${lang}: ${at} should be a list of ${en.length}`);
    return en.forEach((v, i) => compare(v, other[i], lang, `${at}[${i}]`));
  }
  if (en && typeof en === 'object') {
    if (!other || typeof other !== 'object') return problems.push(`${lang}: ${at} missing`);
    Object.keys(en).forEach(k => compare(en[k], other[k], lang, at ? `${at}.${k}` : k));
    Object.keys(other).filter(k => !(k in en)).forEach(k => problems.push(`${lang}: ${at ? at + '.' : ''}${k} is not in English`));
    return;
  }
  if (typeof other !== 'string' || !other.trim()) return problems.push(`${lang}: ${at} missing`);
  if (placeholders(en) !== placeholders(other)) problems.push(`${lang}: ${at} placeholders differ from English`);
  // A long string identical to English is an untranslated one, except the
  // few that are the same on purpose (the studio's name).
  if (en === other && !SAME_ON_PURPOSE.has(at) && en.replace(/<[^>]+>/g, '').length > 24) problems.push(`${lang}: ${at} is still English`);
  if ((en.match(/<b>/g) || []).length !== (other.match(/<b>/g) || []).length) problems.push(`${lang}: ${at} has a different number of <b> than English`);
};
LANGS.filter(l => l !== 'en' && S[l]).forEach(l => compare(S.en, S[l], l, ''));

// ── Write ──────────────────────────────────────────────────────────────────
const written = [];
for (const lang of LANGS.filter(l => S[l])) {
  const dir = lang === 'en' ? '' : `${lang}/`;
  written.push(write(`${dir}index.html`, home(lang)));
  written.push(write(`${dir}support.html`, support(lang)));
  written.push(write(`${dir}404.html`, notFound(lang)));
}

// ── Link check on what was written ─────────────────────────────────────────
// Every root-relative href/src must be a file Pages will serve: '/' and
// '/fr/' are index.html, '/fr/support' is support.html.
const exists = (url) => {
  const p = url.split('#')[0].split('?')[0];
  if (!p.startsWith('/') || p.startsWith('//')) return true;
  const rel = p.endsWith('/') ? `${p}index.html` : (path.extname(p) ? p : `${p}.html`);
  return fs.existsSync(path.join(L.SITE, rel));
};
for (const rel of written) {
  const html = fs.readFileSync(path.join(L.SITE, rel), 'utf8');
  for (const m of html.matchAll(/\s(?:href|src)="([^"]+)"/g)) {
    if (!exists(m[1])) problems.push(`${rel}: broken link ${m[1]}`);
  }
}

console.log(`${written.length} pages written to ${L.SITE}`);
if (problems.length) {
  console.log('\nProblems:');
  problems.forEach(p => console.log('  ! ' + p));
  process.exitCode = 1;
} else {
  console.log('  all languages complete, all links resolve.');
}
