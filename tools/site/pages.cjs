// Generates the marketing site's Home, Support and 404 pages in every
// language (site i18n plan, docs/site-i18n-plan.md).
//
//   node tools/site/pages.cjs
//
// Writes ../StackdSite/{index,support,404}.html (English, at the root) and
// ../StackdSite/<lang>/{index,support,404}.html for fr, it, es, pt.
//
// The copy lives in tools/site/strings/<lang>.cjs; the markup lives here and
// in layout.cjs, so the five languages cannot drift apart in structure. Edit
// the strings, re-run, commit the site repo. Then run legal.cjs (it shares the
// header) and sitemap.cjs.
//
// Before writing anything it checks that every language has every key, the
// same placeholders and the same list lengths as English, and afterwards that
