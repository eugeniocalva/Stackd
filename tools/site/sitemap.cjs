// Regenerates the marketing site's sitemap.xml.
//
//   node tools/site/sitemap.cjs
//
// Each <lastmod> is the commit date of that page in the site repo, so the
// dates are true by construction rather than hand-maintained. Google ignores
// <priority> and <changefreq>, and distrusts <lastmod> when it is inaccurate,
// so this emits <lastmod> only.
//
// Run it after committing a content change to the site, then commit the
// regenerated sitemap.
const path = require('path');
const fs = require('fs');
const { execFileSync } = require('child_process');

const SITE = path.resolve(__dirname, '../../../StackdSite');
const ORIGIN = 'https://stackdplatform.com';

// Cloudflare Pages strips .html, so the canonical URLs are extensionless.
const PAGES = ['index.html', 'support.html', 'privacy.html', 'terms.html'];
const urlFor = f => (f === 'index.html' ? '/' : '/' + f.replace(/\.html$/, ''));

const lastmod = (file) => {
  try {
    const iso = execFileSync('git', ['-C', SITE, 'log', '-1', '--format=%cI', '--', file],
      { encoding: 'utf8' }).trim();
    if (iso) return iso.slice(0, 10);
  } catch { /* fall through to mtime */ }
  return fs.statSync(path.join(SITE, file)).mtime.toISOString().slice(0, 10);
};

const body = PAGES.map(f =>
  `  <url>\n    <loc>${ORIGIN}${urlFor(f)}</loc>\n    <lastmod>${lastmod(f)}</lastmod>\n  </url>`
).join('\n');

const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/site/sitemap.cjs in the app repo. Do not hand-edit. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${body}
</urlset>
`;

const out = path.join(SITE, 'sitemap.xml');
fs.writeFileSync(out, xml, 'utf8');
console.log(xml);
console.log(`wrote ${path.relative(process.cwd(), out)} (${PAGES.length} URLs)`);
